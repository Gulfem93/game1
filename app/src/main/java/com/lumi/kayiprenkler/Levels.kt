package com.lumi.kayiprenkler

/**
 * Harita sembolleri:
 *  .  boş kare        #  duvar (ağaç / kamış / kaya)      L  Lumi'nin başlangıcı
 *  *  ışık parçası    E  renk fidanı       ^  karanlık diken
 *  H  yatay gölge     V  dikey gölge       A  avcı gölge (yaklaşınca kovalar)
 *  C  mavi kristal    D  kapı              ~  su (bulutlarda boşluk)
 *  o  nilüfer (bir kez basılır, sonra batar)
 *  =  buz (engele çarpana kadar kayılır)
 *  ?  gizli ışık parçası (Pıtır gösterene kadar görünmez)
 *  :  görünmez köprü (Pıtır gösterene kadar geçilemez)
 *  P  solmuş çiçek (Lumi yanına gelince Pıtır renk verir)   G  kök kapı (çiçek açınca çekilir)
 *  > < n u  rüzgâr (sağa, sola, yukarı, aşağı iter)
 */

/** Bölge: haritada bir altıgen kart ve ona bağlı ardışık 5 bölüm. Her bölgenin kendi ortamı vardır. */
class Region(val name: String, val first: Int, val count: Int = 5) {
    val last: Int get() = first + count - 1
    operator fun contains(level: Int) = level in first..last
}

enum class Theme { FOREST, LAKE, CAVE, SNOW, CLOUD }

class LevelDef(
    val name: String,
    val restoredText: String,
    val hint: String,
    val accent: Int,
    val leaf: Int,
    val skyTop: Int,
    val skyBottom: Int,
    val shadowStep: Float,
    val map: List<String>,
    /** Toplanan parça yokken ışık yarıçapı (kare). Sis ve mağarada daralır. */
    val light: Float = 2.4f,
    /** Avcı gölgenin bir kare ilerleme süresi (saniye). */
    val hunterStep: Float = 0.55f,
    /** Çözücünün bulduğu en kısa çözümün hamle sayısı (buz kayması ve rüzgâr zinciri tek hamle). */
    val par: Int = 0,
) {
    /** 3 yıldız için en fazla hamle: en kısa çözüm + %15 pay (en az 2). */
    val threeStarMoves: Int get() = par + maxOf(2, (par * 0.15f).toInt() + 1)

    /** 2 yıldız için en fazla hamle: en kısa çözüm + %50 pay (en az 6). */
    val twoStarMoves: Int get() = par + maxOf(6, (par * 0.5f).toInt() + 1)

    fun starsFor(moves: Int): Int = when {
        moves <= threeStarMoves -> 3
        moves <= twoStarMoves -> 2
        else -> 1
    }
}

